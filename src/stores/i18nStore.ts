/** i18n Store 接口 */
interface I18nState {
  locale: string
  translations: Translations
  loading: boolean
  t: (key: string, fallback?: string) => string
  loadTranslations: () => Promise<void>
  setLocale: (locale: string) => Promise<void>
}

export const useI18nStore = create<I18nState>((set, get) => ({
  locale: 'zh-CN',
  translations: zhCNFallback,
  loading: true,

  t: (key: string, fallback?: string) => {
    const { translations } = get()
    return translate(key, translations, fallback)
  },

  loadTranslations: async () => {
    try {
      const locale = await getLocale()
      const translations = await getTranslations(locale)
      set({ locale, translations, loading: false })
    } catch {
      // 后端加载失败时使用内置 fallback / Use built-in fallback when backend loading fails
      set({ locale: 'zh-CN', translations: zhCNFallback, loading: false })
    }
  },

  setLocale: async (locale: string) => {
    try {
      await setApiLocale(locale)
      const translations = await getTranslations(locale)
      set({ locale, translations })
    } catch (e) {
      console.error('Failed to set locale:', e)
    }
  },
}))
